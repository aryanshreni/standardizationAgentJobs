targetCatalogPlain = targetCatalogName.strip("`")
targetSchemaPlain = targetSchemaName.strip("`")
targetTablePlain = targetTableName.strip("`")
metadataFilter = (
    f"lower(table_catalog) = {sql_string_literal(targetCatalogPlain.lower())} "
    f"AND lower(table_schema) = {sql_string_literal(targetSchemaPlain.lower())} "
    f"AND lower(table_name) = {sql_string_literal(targetTablePlain.lower())}"
)
current_table_comment = None
current_column_comments = {}
comments_readable = True
try:
    table_comment_rows = spark.sql(
        f"SELECT comment FROM {targetCatalogName}.information_schema.tables WHERE {metadataFilter}"
    ).collect()
    current_table_comment = table_comment_rows[0][0] if table_comment_rows else None
    for row in spark.sql(
        f"SELECT column_name, comment FROM {targetCatalogName}.information_schema.columns "
        f"WHERE {metadataFilter}"
    ).collect():
        current_column_comments[str(row[0]).lower()] = row[1]
except Exception as comment_read_error:
    comments_readable = False
    print(f"WARNING could not read comments ({type(comment_read_error).__name__})")

target_table_columns_now = set(
    field.name for field in spark.table(f"{targetCatalogName}.{targetSchemaName}.{targetTableName}").schema
)
comment_statements = []
if tableCommentLiteral and not (
    comments_readable
    and normalize_comment_text(current_table_comment) == normalize_comment_text(tableDescription)
):
    comment_statements.append(
        f"COMMENT ON TABLE {targetCatalogName}.{targetSchemaName}.{targetTableName} "
        f"IS {tableCommentLiteral}"
    )
for m in columnMapping + etlMetadataColumns:
    column_comment_literal = sql_comment_literal(m.get("description"))
    if not column_comment_literal or m["target_col"] not in target_table_columns_now:
        continue
    if comments_readable and (
        normalize_comment_text(current_column_comments.get(m["target_col"].lower()))
        == normalize_comment_text(m.get("description"))
    ):
        continue
    comment_statements.append(
        f"ALTER TABLE {targetCatalogName}.{targetSchemaName}.{targetTableName} "
        f"ALTER COLUMN `{m['target_col']}` COMMENT {column_comment_literal}"
    )
for comment_statement in comment_statements:
    spark.sql(comment_statement)
print(f"metadata sync: {len(comment_statements)} comment statement(s)")

