def get_ddl_type(mapping_entry):
    dtype = mapping_entry["data_type"].upper()
    last_tx = mapping_entry["transformations"][-1].upper()
    if last_tx in ("DATE_CAST", "DATE_JULIAN", "DATE_MMDDYY", "DATE_MMDDYYYY"):
        return "DATE"
    return dtype

ddl_cols = [f"`source_system` STRING", f"`{linkKeyName}` BIGINT"]
